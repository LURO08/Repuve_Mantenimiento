    def ejecutar_consulta_sql_thread(self):
        query = self.sql_editor.get("1.0", tk.END).strip()
        if not query:
            messagebox.showwarning("Aviso", "Escribe una consulta SQL antes de ejecutar.")
            return

        self.lbl_sql_status.config(text="Ejecutando consulta...")
        threading.Thread(target=self._ejecutar_consulta_sql_worker, args=(query,), daemon=True).start()

    def _ejecutar_consulta_sql_worker(self, query):
        target = self.target_sql.get()
        t0 = time.time()
        conn = None
        try:
            motor, cfg_o, uri_o, uri_d = self._obtener_configuraciones()

            if target == "destino":
                conn = psycopg2.connect(uri_d)
            else:
                conn = self._conectar_origen(motor, cfg_o, uri_o)

            cur = conn.cursor()
            cur.execute(query)
            elapsed = time.time() - t0

            # Verificar si la consulta devolvió filas (SELECT / RETURNING)
            if cur.description:
                columnas = [d[0] for d in cur.description]
                filas = cur.fetchall()
                conn.commit()
                cur.close()
                conn.close()

                self.root.after(0, lambda: self._mostrar_resultados_tabla(columnas, filas, elapsed))
                self.root.after(0, lambda: self._log_sql(f"Query SELECT completada en {elapsed:.3f}s. {len(filas)} filas obtenidas."))
                self.root.after(0, lambda: self.lbl_sql_status.config(text=f"✔ Éxito: {len(filas)} filas en {elapsed:.3f}s"))
            else:
                conn.commit()
                rowcount = cur.rowcount
                cur.close()
                conn.close()

                mensaje_exito = f"Comando ejecutado exitosamente en {elapsed:.3f}s. Filas afectadas: {rowcount if rowcount >= 0 else 'N/A'}."
                self.root.after(0, lambda: self._mostrar_mensaje_dml(mensaje_exito, elapsed))
                self.root.after(0, lambda: self._log_sql(mensaje_exito))
                self.root.after(0, lambda: self.lbl_sql_status.config(text=f"✔ Ejecutado en {elapsed:.3f}s (Afectadas: {rowcount})"))

        except Exception as e:
            if conn:
                try:
                    conn.rollback()
                    conn.close()
                except Exception:
                    pass
            elapsed = time.time() - t0
            err_msg = str(e)
            self.root.after(0, lambda: self._mostrar_error_sql(err_msg, elapsed))
            self.root.after(0, lambda: self._log_sql(f"Error al ejecutar: {err_msg}", error=True))
            self.root.after(0, lambda: self.lbl_sql_status.config(text="✖ Error en consulta."))

    def _mostrar_resultados_tabla(self, columnas, filas, elapsed):
        self.nb_sql_results.select(0)  # Pestaña de tabla
        self.sql_tree.delete(*self.sql_tree.get_children())

        # Configurar columnas dinámicamente
        self.sql_tree["columns"] = columnas
        for col in columnas:
            self.sql_tree.heading(col, text=col, anchor="w")
            # Ancho proporcional inicial
            ancho = max(len(col) * 11, 100)
            self.sql_tree.column(col, width=ancho, minwidth=60, anchor="w")

        # Insertar filas (formatear nulos y fechas)
        for fila in filas:
            fila_formateada = ["" if v is None else str(v) for v in fila]
            self.sql_tree.insert("", "end", values=fila_formateada)

        self.lbl_sql_metrics.config(text=f"📊 Total de registros: {len(filas):,}   |   Tiempo de ejecución: {elapsed:.3f}s   |   Columnas: {len(columnas)}")

