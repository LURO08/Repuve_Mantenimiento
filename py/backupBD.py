    def _mapear_tipo_mysql_a_postgres(self, col_type, extra):
        c_type = col_type.lower()
        if "auto_increment" in extra.lower():
            return "BIGSERIAL" if "bigint" in c_type else "SERIAL"
        if "tinyint(1)" in c_type or c_type == "boolean":
            return "BOOLEAN"
        if "int" in c_type:
            if "bigint" in c_type:
                return "BIGINT"
            if "smallint" in c_type:
                return "SMALLINT"
            return "INTEGER"
        if "varchar" in c_type or "char" in c_type:
            return col_type.upper()
        if "text" in c_type or "longtext" in c_type or "mediumtext" in c_type:
            return "TEXT"
        if "decimal" in c_type or "numeric" in c_type or "double" in c_type or "float" in c_type:
            return col_type.upper()
        if "datetime" in c_type or "timestamp" in c_type:
            return "TIMESTAMP WITHOUT TIME ZONE"
        if "date" in c_type:
            return "DATE"
        if "json" in c_type:
            return "JSONB"
        return "TEXT"

    def clonar_estructura_tabla(self, motor, cur_origen, cur_remota, conn_remota, tabla):
        col_defs = []
        pk_cols = []

        if motor == "mysql":
            cur_origen.execute(f"DESCRIBE `{tabla}`;")
            columnas = cur_origen.fetchall()

            for col_name, data_type, is_null, key, default_val, extra in columnas:
                tipo_pg = self._mapear_tipo_mysql_a_postgres(data_type, extra)

                if "SERIAL" in tipo_pg:
                    col_def = f'"{col_name}" {tipo_pg}'
                else:
                    null_str = "NOT NULL" if is_null == "NO" else "NULL"
                    default_str = ""
                    if default_val is not None:
                        default_str = f"DEFAULT '{default_val}'" if not str(default_val).isdigit() else f"DEFAULT {default_val}"
                    col_def = f'"{col_name}" {tipo_pg} {default_str} {null_str}'.strip()

                col_defs.append(col_def)
                if key == "PRI":
                    pk_cols.append(f'"{col_name}"')
        else:
            cur_origen.execute(
                """
                SELECT c.column_name, c.data_type, c.character_maximum_length, c.is_nullable, c.column_default, c.udt_name,
                       COALESCE(c.is_identity, 'NO') as is_identity,
                       COALESCE(c.identity_generation, '') as identity_gen
                FROM information_schema.columns c
                WHERE c.table_schema = 'public' AND c.table_name = %s
                ORDER BY c.ordinal_position;
            """,
                (tabla,),
            )
            columnas = cur_origen.fetchall()

            cur_origen.execute(
                """
                SELECT kcu.column_name
                FROM information_schema.table_constraints tc
                JOIN information_schema.key_column_usage kcu 
                  ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema
                WHERE tc.constraint_type = 'PRIMARY KEY' AND tc.table_schema = 'public' AND tc.table_name = %s;
            """,
                (tabla,),
            )
            pk_cols = [f'"{r[0]}"' for r in cur_origen.fetchall()]

            for col_name, data_type, max_len, is_null, default_val, udt_name, is_identity, identity_gen in columnas:
                tipo_sql = udt_name
                if max_len:
                    tipo_sql = f"{data_type}({max_len})"
                elif data_type in [
                    "integer",
                    "bigint",
                    "smallint",
                    "boolean",
                    "text",
                    "json",
                    "jsonb",
                    "date",
                    "timestamp without time zone",
                    "timestamp with time zone",
                ]:
                    tipo_sql = data_type

                # Manejo de IDENTITY y SERIAL en PostgreSQL
                if is_identity == "YES":
                    gen = "BY DEFAULT" if "BY DEFAULT" in identity_gen.upper() else "BY DEFAULT"
                    col_def = f'"{col_name}" {tipo_sql} GENERATED {gen} AS IDENTITY'
                elif default_val and "nextval" in str(default_val):
                    tipo_sql = "BIGSERIAL" if "bigint" in tipo_sql else "SERIAL"
                    col_def = f'"{col_name}" {tipo_sql}'
                else:
                    null_str = "NOT NULL" if is_null == "NO" else "NULL"
                    default_str = f"DEFAULT {default_val}" if default_val else ""
                    col_def = f'"{col_name}" {tipo_sql} {default_str} {null_str}'.strip()

                col_defs.append(col_def)

        if pk_cols:
            col_defs.append(f'PRIMARY KEY ({", ".join(pk_cols)})')

        ddl = f'CREATE TABLE IF NOT EXISTS "{tabla}" (\n  ' + ",\n  ".join(col_defs) + "\n);"
        cur_remota.execute(ddl)
        conn_remota.commit()

    def ejecutar_migracion(self, tablas):
        try:
            motor, cfg_o, uri_o, uri_d = self._obtener_configuraciones()
            self.log(f"\n================ Iniciando Migración [{motor.upper()} -> POSTGRESQL] ================")

            conn_origen = self._conectar_origen(motor, cfg_o, uri_o)
            conn_remota = psycopg2.connect(uri_d)

            cur_origen = conn_origen.cursor()
            cur_remota = conn_remota.cursor()

            for tabla in tablas:
                self.datos_tablas[tabla]["status"] = "Migrando..."
                self.root.after(0, lambda t=tabla: self._actualizar_fila_tree(t))

                self.log(f"\n[+] Verificando/Creando estructura para '{tabla}'...")
                self.clonar_estructura_tabla(motor, cur_origen, cur_remota, conn_remota, tabla)

                # Extraer datos
                if motor == "mysql":
                    cur_origen.execute(f"SELECT * FROM `{tabla}`;")
                else:
                    cur_origen.execute(f'SELECT * FROM "{tabla}";')

                filas = cur_origen.fetchall()

                if not filas:
                    self.log(f"    -> Tabla '{tabla}' vacía. Estructura lista.")
                    self.datos_tablas[tabla]["status"] = "Vacía / OK"
                    self.root.after(0, lambda t=tabla: self._actualizar_fila_tree(t))
                    continue

                columnas = [f'"{desc[0]}"' for desc in cur_origen.description]
                nombres_cols = ", ".join(columnas)
                query_insert = f'INSERT INTO "{tabla}" ({nombres_cols}) VALUES %s ON CONFLICT DO NOTHING;'

                batch_size = 1000
                for i in range(0, len(filas), batch_size):
                    lote = filas[i : i + batch_size]
                    execute_values(cur_remota, query_insert, lote)

                conn_remota.commit()
                self.datos_tablas[tabla]["status"] = "Completado"
                self.root.after(0, lambda t=tabla: self._actualizar_fila_tree(t))
                self.log(f"    -> Éxito: {len(filas)} filas pasadas a '{tabla}'.")

            # Sincronización robusta de secuencias e identidades en PostgreSQL
            self.log("\n[+] Sincronizando secuencias de IDs en destino...")
            for tab in tablas:
                try:
                    cur_remota.execute("""
                        SELECT column_name 
                        FROM information_schema.columns 
                        WHERE table_schema = 'public' AND table_name = %s
                          AND (is_identity = 'YES' OR column_default LIKE '%nextval%');
                    """, (tab,))
                    cols_seq = cur_remota.fetchall()
                    for (c_name,) in cols_seq:
                        cur_remota.execute(f"""
                            SELECT setval(pg_get_serial_sequence('"{tab}"', '{c_name}'), 
                                          COALESCE((SELECT MAX("{c_name}") FROM "{tab}"), 1));
                        """)
                except Exception as seq_err:
                    self.log(f"    [!] Advertencia al sincronizar secuencia en '{tab}': {seq_err}")
            conn_remota.commit()

            self.log("\n[✓] MIGRACIÓN FINALIZADA CON ÉXITO.")
            messagebox.showinfo("Completado", "La migración finalizó correctamente.")

            cur_origen.close()
            cur_remota.close()
            conn_origen.close()
            conn_remota.close()

        except Exception as e:
            self.log(f"\n[!] Error crítico: {e}")
            messagebox.showerror("Error en Migración", str(e))
        finally:
            self.btn_migrar.config(state="normal")

