    def _reparar_auto_increment_render_worker(self):
        _, _, _, uri_d = self._obtener_configuraciones()
        self.root.after(0, lambda: self.nb_sql_results.select(1))
        self.root.after(0, lambda: self._log_sql("Iniciando análisis y reparación de Auto-Increment (IDENTITY) en Render..."))

        try:
            conn = psycopg2.connect(uri_d)
            cur = conn.cursor()

            # Buscar todas las columnas de tablas con clave primaria entera sin identity o sin secuencia
            cur.execute("""
                SELECT c.table_name, c.column_name
                FROM information_schema.columns c
                JOIN information_schema.table_constraints tc 
                  ON tc.table_name = c.table_name AND tc.table_schema = c.table_schema
                JOIN information_schema.key_column_usage kcu 
                  ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema AND kcu.column_name = c.column_name
                WHERE c.table_schema = 'public'
                  AND tc.constraint_type = 'PRIMARY KEY'
                  AND c.data_type IN ('integer', 'bigint', 'smallint')
                  AND COALESCE(c.is_identity, 'NO') = 'NO'
                  AND (c.column_default IS NULL OR c.column_default NOT LIKE '%nextval%')
                  AND c.table_name IN (
                      SELECT table_name
                      FROM information_schema.key_column_usage
                      WHERE table_schema = 'public' AND constraint_name = tc.constraint_name
                      GROUP BY table_name
                      HAVING COUNT(*) = 1
                  )
                ORDER BY c.table_name;
            """)
            tablas_a_reparar = cur.fetchall()

            if not tablas_a_reparar:
                self.root.after(0, lambda: self._log_sql("✔ Todas las tablas ya cuentan con IDENTITY o secuencia configurada correctamente."))
                self.root.after(0, lambda: messagebox.showinfo("Información", "No se encontraron tablas pendientes de reparación. Todas las secuencias e identidades están en orden."))
                cur.close()
                conn.close()
                return

            reparadas = 0
            for t, col in tablas_a_reparar:
                try:
                    cur.execute(f'ALTER TABLE "{t}" ALTER COLUMN "{col}" ADD GENERATED BY DEFAULT AS IDENTITY;')
                    cur.execute(f"""
                        SELECT setval(pg_get_serial_sequence('"{t}"', '{col}'), COALESCE((SELECT MAX("{col}") FROM "{t}"), 1));
                    """)
                    conn.commit()
                    reparadas += 1
                    msg_ok = f" ✔ {t}.{col} -> Configurado con GENERATED BY DEFAULT AS IDENTITY (Secuencia sincronizada)."
                    self.root.after(0, lambda m=msg_ok: self._log_sql(m))
                except Exception as err_tab:
                    conn.rollback()
                    msg_err = f" ✖ Error reparando {t}.{col}: {err_tab}"
                    self.root.after(0, lambda m=msg_err: self._log_sql(m, error=True))

            cur.close()
            conn.close()

            res_final = f"Proceso finalizado. Se repararon {reparadas} de {len(tablas_a_reparar)} tablas candidatas en Render."
            self.root.after(0, lambda: self._log_sql(res_final))
            self.root.after(0, lambda: messagebox.showinfo("Reparación Completada", res_final))
            self.root.after(0, lambda: self.lbl_sql_status.config(text=f"✔ Reparadas {reparadas} tablas."))

        except Exception as e:
            self.root.after(0, lambda: self._log_sql(f"Error general en reparación: {e}", error=True))
            self.root.after(0, lambda: messagebox.showerror("Error", f"Fallo al ejecutar la reparación:\n{e}"))


