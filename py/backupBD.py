    def _cargar_plantilla_sql(self):
        nombre = self.combo_plantillas.get()
        if nombre in PLANTILLAS_SQL:
            self.sql_editor.delete("1.0", tk.END)
            self.sql_editor.insert("1.0", PLANTILLAS_SQL[nombre])

    def _set_sql_and_run(self, query):
        self.sql_editor.delete("1.0", tk.END)
        self.sql_editor.insert("1.0", query)
        self.ejecutar_consulta_sql_thread()

    def _limpiar_editor_sql(self):
        self.sql_editor.delete("1.0", tk.END)

    def _log_sql(self, mensaje, error=False):
        timestamp = datetime.datetime.now().strftime("%H:%M:%S")
        self.sql_log.configure(state="normal")
        prefijo = "[ERROR]" if error else "[INFO]"
        self.sql_log.insert(tk.END, f"[{timestamp}] {prefijo} {mensaje}\n")
        self.sql_log.see(tk.END)
        self.sql_log.configure(state="disabled")

    def _crear_input(self, parent, label, default, r, c, w):
        ttk.Label(parent, text=label).grid(row=r, column=c, sticky="w", padx=(4, 1))
        e = ttk.Entry(parent, width=w)
        e.insert(0, default)
        e.grid(row=r, column=c + 1, padx=(1, 4), pady=2)
